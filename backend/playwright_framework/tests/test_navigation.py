import pytest
import allure
from playwright.async_api import Page, expect


@allure.feature("Navigation Architecture")
class TestNavigation:
    """Automated checks for page routing, navigation bars, and title integrity."""

    @allure.story("Root Navigation & Title Validation")
    @allure.severity(allure.severity_level.CRITICAL)
    @pytest.mark.asyncio
    async def test_page_loads_with_valid_title(self, page: Page):
        """Verifies that the target page opens without crash and contains a document title."""
        with allure.step("Navigate to initial application URL"):
            response = await page.goto("https://example.com", wait_until="domcontentloaded")
            assert response and response.status < 400, f"Page load failed with status {response.status if response else 'None'}"

        with allure.step("Assert document title exists"):
            title = await page.title()
            assert len(title.strip()) > 0, "Page has an empty document title"

    @allure.story("Navigation Links Sanity")
    @allure.severity(allure.severity_level.NORMAL)
    @pytest.mark.asyncio
    async def test_links_have_valid_href(self, page: Page):
        """Verifies all anchor tags in navigation have non-empty href attributes."""
        await page.goto("https://example.com")
        links = await page.locator("a").all()
        for i, link in enumerate(links[:10]):
            href = await link.get_attribute("href")
            assert href is not None, f"Link at index {i} has null href"

