"""
Script Generator Utility
Renders Python Playwright Page Object Model classes and pytest test definitions.
"""
from __future__ import annotations

import re
from typing import Any, Dict, List


class ScriptGenerator:
    """Dynamically outputs Python test source code for discovered applications."""

    @staticmethod
    def generate_page_class(page_name: str, elements: List[Dict[str, Any]], page_url: str = "") -> str:
        """Render a Page Object Model class."""
        class_name = "".join(w.capitalize() for w in re.split(r"[\s_-]", page_name)) + "Page"
        
        locators_code = []
        for elem in elements:
            sel = elem.get("selector")
            lbl = elem.get("label", "element")
            const_name = re.sub(r"[^A-Z0-9_]", "_", lbl.upper().replace(" ", "_")).strip("_")
            if sel and const_name:
                locators_code.append(f'    {const_name} = "{sel}"')

        locators_str = "\n".join(locators_code) or "    # No explicit locators found"

        return f'''"""
{class_name} Page Object
Auto-generated by AI Autonomous Testing Agent
"""
from pages.base_page import BasePage
from playwright.async_api import Page


class {class_name}(BasePage):
    URL = "{page_url}"

{locators_str}

    def __init__(self, page: Page):
        super().__init__(page)

    async def navigate(self):
        await self.page.goto(self.URL, wait_until="networkidle")
'''

    @staticmethod
    def generate_test_class(feature_name: str, test_cases: List[Dict[str, Any]], page_module: str, page_class: str) -> str:
        """Render a pytest test suite file."""
        tests_code = []
        for tc in test_cases:
            func_name = re.sub(r"[^a-zA-Z0-9_]", "_", tc.get("name", "test").lower())
            if not func_name.startswith("test_"):
                func_name = "test_" + func_name

            tests_code.append(f'''
    @allure.story("{tc.get('name', 'Test')}")
    @pytest.mark.asyncio
    async def {func_name}(self, page: Page):
        page_obj = {page_class}(page)
        await page_obj.navigate()
        assert await page.title() != ""
''')

        tests_str = "\n".join(tests_code)

        return f'''"""
{feature_name} Test Suite
Auto-generated by AI Autonomous Testing Agent
"""
import pytest
import allure
from playwright.async_api import Page
from pages.{page_module} import {page_class}


@allure.feature("{feature_name}")
class Test{page_class.replace("Page", "")}:
{tests_str}
'''

