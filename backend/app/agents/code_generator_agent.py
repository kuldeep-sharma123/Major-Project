class CodeGeneratorAgent:
    """
    Agent 4: Playwright Code Generator
    
    Generates production-ready Python Playwright scripts following:
    - Page Object Model (POM) pattern
    - Allure reporting decorators
    - pytest fixtures
    - Self-healing locator usage
    """

    def __init__(self):
        self.framework_path = settings.PLAYWRIGHT_FRAMEWORK_PATH
        self.pages_dir = os.path.join(self.framework_path, "pages")
        self.tests_dir = os.path.join(self.framework_path, "tests")
        self.generated_files: List[str] = []
        
        # Ensure directories exist
        os.makedirs(self.pages_dir, exist_ok=True)
        os.makedirs(self.tests_dir, exist_ok=True)
        
        logger.info("⚙️ Code Generator Agent initialized")

    async def generate_all_scripts(
        self,
        test_cases: List[Dict[str, Any]],
        page_analyses: List[Dict[str, Any]],
        app_name: str,
        app_url: str,
    ) -> List[str]:
        """
        Generate all Playwright scripts from test cases.
        
        Args:
            test_cases: All generated test cases
            page_analyses: Page analysis results
            app_name: Application name
            app_url: Application URL
            
        Returns:
            List of generated file paths
        """
        logger.info(f"🎭 Generating Playwright scripts for {len(test_cases)} test cases...")
        
        # Generate base page first
        await self._generate_base_page()
        
        # Group test cases by page type
        cases_by_page = {}
        for tc in test_cases:
            page_type = tc.get("page_type", "general")
            if page_type not in cases_by_page:
                cases_by_page[page_type] = []
            cases_by_page[page_type].append(tc)
        
        # Generate page objects and tests for each page type
        for page_type, cases in cases_by_page.items():
            page_analysis = next(
                (p for p in page_analyses if p.get("page_type") == page_type),
                None,
            )
            
            # Generate page class
            page_file = await self._generate_page_class(
                page_type, page_analysis, app_url
            )
            if page_file:
                self.generated_files.append(page_file)
            
            # Generate test file
            test_file = await self._generate_test_file(
                page_type, cases, app_name
            )
            if test_file:
                self.generated_files.append(test_file)
        
        # Generate conftest.py
        await self._generate_conftest(app_url)
        
        logger.success(f"✅ Generated {len(self.generated_files)} automation files")
        return self.generated_files

    async def _generate_base_page(self) -> None:
        """Write the BasePage class to the framework."""
        base_path = os.path.join(self.pages_dir, "base_page.py")
        with open(base_path, "w", encoding="utf-8") as f:
            f.write(BASE_PAGE_TEMPLATE)
        logger.debug("✓ Generated base_page.py")

    async def _generate_page_class(
        self,
        page_type: str,
        page_analysis: Optional[Dict[str, Any]],
        app_url: str,
    ) -> Optional[str]:
        """Generate a Page Object class for a specific page type."""
        class_name = self._to_class_name(page_type) + "Page"
        module_name = page_type.lower().replace(" ", "_").replace("-", "_") + "_page"
        file_path = os.path.join(self.pages_dir, f"{module_name}.py")
        
        # Build locators from page analysis
        locators = self._build_locators_code(page_analysis)
        
        # Build methods from page analysis  
        methods = self._build_methods_code(page_type, page_analysis)
        
        page_url = (page_analysis or {}).get("url", app_url)
        
        content = PAGE_CLASS_TEMPLATE.format(
            page_name=page_type.replace("_", " ").title(),
            class_name=class_name,
            page_url=page_url,
            locators=locators,
            methods=methods,
        )
        
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(content)
        
        logger.debug(f"✓ Generated {module_name}.py")
        return f"pages/{module_name}.py"

    async def _generate_test_file(
        self,
        page_type: str,
        test_cases: List[Dict[str, Any]],
        app_name: str,
    ) -> Optional[str]:
        """Generate a pytest test file for a specific page type."""
        class_name = self._to_class_name(page_type) + "Page"
        module_name = page_type.lower().replace(" ", "_").replace("-", "_") + "_page"
        test_module_name = f"test_{module_name.replace('_page', '')}"
        file_path = os.path.join(self.tests_dir, f"{test_module_name}.py")
        
        feature_name = f"{app_name} - {page_type.replace('_', ' ').title()}"
        
        # Generate test methods
        test_methods = []
        for tc in test_cases[:20]:  # Limit to 20 tests per file
            method = self._generate_test_method(tc, class_name, module_name)
            test_methods.append(method)
        
        content = TEST_FILE_TEMPLATE.format(
            feature_name=feature_name,
            page_module=module_name,
            page_class=class_name,
            class_suffix=self._to_class_name(page_type),
            test_methods="\n".join(test_methods),
        )
        
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(content)
        
        logger.debug(f"✓ Generated {test_module_name}.py")
        return f"tests/{test_module_name}.py"

