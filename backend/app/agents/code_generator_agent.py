BASE_PAGE_TEMPLATE = '''"""
Base Page Object
Provides self-healing locator strategy and common page interactions.
Auto-generated by AI Autonomous Testing Agent
"""

import asyncio
from typing import Optional, List

import allure
from loguru import logger
from playwright.async_api import Page, Locator, expect


class BasePage:
    """
    Base class for all Page Objects.
    Implements self-healing locators and common interaction patterns.
    """

    DEFAULT_TIMEOUT = 10000  # 10 seconds

    def __init__(self, page: Page):
        self.page = page

    async def navigate(self, url: str):
        """Navigate to URL and wait for DOM content loaded."""
        await self.page.goto(url, wait_until="domcontentloaded", timeout=self.DEFAULT_TIMEOUT)
        await self.page.wait_for_timeout(1000)

    async def find_element(
        self,
        primary_selector: str,
        fallbacks: Optional[List[str]] = None,
        role: Optional[str] = None,
        name: Optional[str] = None,
        text: Optional[str] = None,
    ) -> Optional[Locator]:
        """
        Self-healing locator strategy.
        Tries selectors in order until one resolves.
        
        Strategy order:
        1. Primary CSS selector
        2. Fallback selectors
        3. Role-based locator
        4. Text-based locator
        5. Partial text match
        """
        strategies = []
        
        # 1. Primary
        strategies.append(("CSS", lambda: self.page.locator(primary_selector)))
        
        # 2. Fallbacks
        for fb in (fallbacks or []):
            strategies.append(("CSS_Fallback", lambda s=fb: self.page.locator(s)))
        
        # 3. Role-based
        if role:
            name_val = name or text
            if name_val:
                strategies.append(
                    ("Role", lambda: self.page.get_by_role(role, name=name_val))
                )
        
        # 4. Text-based
        if text:
            strategies.append(("Text", lambda t=text: self.page.get_by_text(t, exact=False)))
        
        # 5. Partial text
        if name:
            strategies.append(("Label", lambda n=name: self.page.get_by_label(n)))

        for strategy_name, strategy_fn in strategies:
            try:
                locator = strategy_fn()
                await locator.wait_for(timeout=3000, state="attached")
                count = await locator.count()
                if count > 0:
                    logger.debug(f"✓ Locator found via {strategy_name}: {primary_selector}")
                    return locator
            except Exception:
                logger.debug(f"✗ Strategy {strategy_name} failed for: {primary_selector}")
                continue

        logger.warning(f"⚠️ All locator strategies failed for: {primary_selector}")
        return None

    async def click(self, selector: str, **kwargs) -> None:
        """Click an element with self-healing."""
        locator = await self.find_element(selector)
        if locator:
            await locator.click(**kwargs)
        else:
            raise Exception(f"Cannot click: element not found with selector '{selector}'")

    async def fill(self, selector: str, value: str) -> None:
        """Fill an input field with self-healing."""
        locator = await self.find_element(selector)
        if locator:
            await locator.clear()
            await locator.fill(value)
        else:
            raise Exception(f"Cannot fill: element not found with selector '{selector}'")

    async def get_text(self, selector: str) -> str:
        """Get text content of an element."""
        locator = await self.find_element(selector)
        if locator:
            return await locator.inner_text()
        return ""

    async def is_visible(self, selector: str) -> bool:
        """Check if an element is visible."""
        try:
            locator = await self.find_element(selector)
            return await locator.is_visible() if locator else False
        except Exception:
            return False

    async def take_screenshot(self, name: str) -> str:
        """Take a screenshot and attach to Allure report."""
        screenshot_bytes = await self.page.screenshot(full_page=True)
        allure.attach(
            screenshot_bytes,
            name=name,
            attachment_type=allure.attachment_type.PNG,
        )
        return name

    async def wait_for_navigation(self, timeout: int = 10000) -> None:
        """Wait for page navigation to complete."""
        try:
            await self.page.wait_for_load_state("domcontentloaded", timeout=timeout)
        except Exception:
            pass
'''

